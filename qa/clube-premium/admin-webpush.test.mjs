import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const get=(file)=>readFileSync(new URL('../../'+file,import.meta.url),'utf8')
test('PWA do administrador, web push visível e navegação segura',()=>{
 const m=JSON.parse(get('public/clube-admin.webmanifest'))
 assert.equal(m.display,'standalone')
 assert.ok(m.start_url.startsWith('/clube'))
 const sw=get('public/clube-push-sw.js')
 assert.match(sw,/addEventListener\('push'/)
 assert.match(sw,/registration\.showNotification/)
 assert.match(sw,/addEventListener\('notificationclick'/)
 assert.match(sw,/url\.origin!==self\.location\.origin/)
 assert.doesNotMatch(sw,/addEventListener\('fetch'/)
})
test('API só autoriza administradores reais e bloqueia pedidos externos',()=>{
 const api=get('clube/push/admin-handler.mjs')
 assert.match(get('api/clube/student-connections.js'),/npv_admin_route'\)===\x27push\x27/)
 assert.match(get('vercel.json'),/api\/clube\/admin-push/)
 for(const phrase of ["auth.getUser","from('clube_admins')","admin_required","timingSafeEqual","NPV_PUSH_WEBHOOK_SECRET","NPV_VAPID_PRIVATE_KEY","clube_admin_push_subscriptions"])assert.ok(api.includes(phrase),phrase)
 assert.match(api,/isStillPending\(svc,kind,id\)/)
 assert.match(api,/data\?\.status==='review'/)
 assert.match(api,/id\.length>320/)
 assert.match(get('clube/migrations/20261101_admin_webpush_story_review_fix.sql'),/new\.status='review'/)
 assert.match(api,/data\.is_test!==true/)
 assert.doesNotMatch(api,/VITE_NPV_VAPID_PRIVATE/)
})
test('Sininho apenas no administrador com ativação por toque e teste',()=>{
 const main=get('src/ClubeNPVOnline.jsx'),ui=get('src/ClubeAdminPush.jsx')
 assert.match(main,/<ClubeAdminPush session=\{session\} onNavigate=\{setTab\}\/>/)
 assert.match(main,/\{tab==='inicio'&&isAdmin&&<>/)
 assert.match(ui,/Notification\.requestPermission\(\)/)
 assert.match(ui,/pushManager\.subscribe/)
 assert.match(ui,/action:'test'/)
 assert.match(ui,/setInterval\(refresh,60000\)/)
})
test('Migração protege assinaturas e só aciona novos pedidos válidos',()=>{
 const s=get('clube/migrations/20261101_admin_webpush_free.sql')
 assert.match(s,/enable row level security/gi)
 assert.match(s,/revoke all on table public\.clube_admin_push_subscriptions from anon, authenticated/)
 assert.match(s,/vault\.decrypted_secrets/)
 assert.match(s,/net\.http_post/)
 assert.match(s,/after insert on public\.clube_redemptions/)
 assert.match(s,/after update of email_confirmed_at on auth\.users/)
 assert.match(s,/new\.is_test is distinct from true/)
})
test('web-push é fixado, sem SMS, WhatsApp ou serviços pagos',()=>{
 const p=JSON.parse(get('package.json'))
 assert.equal(p.dependencies['web-push'],undefined)
 const crypto=get('clube/push/web-push.mjs')
 assert.match(crypto,/hkdfSync/)
 assert.match(crypto,/createCipheriv/)
 assert.match(crypto,/createPrivateKey/)
 assert.doesNotMatch(get('src/ClubeAdminPush.jsx'),/Telegram|OneSignal|WhatsApp/)
})
